"""Shared state schema for the LangGraph orchestration workflow."""

from typing import Annotated, Any, Dict, List, Optional, TypedDict
import operator


def merge_specialist_results(left: Dict[str, str], right: Dict[str, str]) -> Dict[str, str]:
    """Reducer to merge specialist results dictionary instead of replacing it."""
    if left is None:
        left = {}
    if right is None:
        right = {}
    return {**left, **right}


def merge_metadata(left: Dict[str, Any], right: Dict[str, Any]) -> Dict[str, Any]:
    """Reducer to merge metadata dictionary instead of replacing it."""
    if left is None:
        left = {}
    if right is None:
        right = {}
    return {**left, **right}


class AgentState(TypedDict):
    """The State schema representing the workspace of our Agentic RAG workflow."""

    original_query: str
    """The raw input query entered by the user."""

    understood_query: Optional[str]
    """The query rephrased or clarified by the Query Understanding agent."""

    intent: Optional[str]
    """The classification of the user's intent."""

    plan: Optional[List[str]]
    """The list of specialist agent names to invoke, decided by the Planner."""

    relevant_context: Optional[List[str]]
    """The context retrieved from the RAG retriever interface."""

    specialist_results: Annotated[Dict[str, str], merge_specialist_results]
    """Results from specialist agents, keyed by the specialist's name."""

    reasoning: Optional[str]
    """Synthesis or logic generated by the Reasoning Agent."""

    final_answer: Optional[Dict[str, Any]]
    """Synthesized structured final answer generated by the Aggregator."""

    errors: Annotated[List[str], operator.add]
    """Errors encountered during execution, appended sequentially."""

    metadata: Annotated[Dict[str, Any], merge_metadata]
    """Execution metadata, such as model details, latencies, or token usage."""

    user_context: Optional[Dict[str, Any]]
    """The authenticated user context (id, email, role, department) passed from chat routes."""
